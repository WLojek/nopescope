import assert from "node:assert/strict";
import { containsAny, matchAuthor, matchLanguage, modelRulesFor, questionFor, PACKS, defaultRules } from "../src/shared/rules.js";
assert.ok(containsAny("new gta 6 trailer", ["gta 6"]));
assert.ok(containsAny("GTA VI story", ["gta vi"]));
assert.ok(!containsAny("megtastic", ["gta"]));
assert.ok(containsAny("lol jason!!", ["jason"]));
assert.ok(containsAny("zażółć gęślą", ["gęślą"]));
assert.ok(!containsAny("gęśląja", ["gęślą"]));
assert.ok(matchAuthor({ authors: ["@ElonMusk"] }, { author: "@elonmusk" }));
assert.ok(matchAuthor({ authors: ["elonmusk"] }, { author: "@elonmusk" }));
assert.ok(matchAuthor({ authors: ["u/spez"] }, { author: "u/spez" }));
assert.ok(matchAuthor({ authors: ["Some Channel"] }, { author: "", authorName: "some channel" }));
assert.ok(!matchAuthor({ authors: ["@a"] }, { author: "@ab" }));
assert.ok(matchLanguage({ languages: ["ru"], languageMode: "block" }, { code: "ru", reliable: true }));
assert.ok(!matchLanguage({ languages: ["ru"], languageMode: "block" }, { code: "ru", reliable: false }));
assert.ok(matchLanguage({ languages: ["en", "pl"], languageMode: "only" }, { code: "de", reliable: true }));
const gta = defaultRules();
assert.equal(modelRulesFor(gta, "x.com", "just a cat picture").length, 0);
assert.equal(modelRulesFor(gta, "x.com", "lucia looks great in the trailer").length, 1);
assert.ok(containsAny("can't wait for #gta6!!", gta.find((r) => r.kind === "keyword").keywords));
assert.ok(!containsAny("gta 5 online update", gta.find((r) => r.kind === "keyword").keywords));
assert.equal(questionFor({ topic: "polityka" }), "Is this text about polityka?");
assert.equal(questionFor({ topic: "piłka nożna" }), "Czy ten tekst dotyczy tematu: piłka nożna?");
assert.equal(PACKS.length >= 3, true);
console.log("rules tests passed");
